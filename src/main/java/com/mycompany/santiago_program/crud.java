    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String product_name = txtFirstname.getText().trim();
        String price = txtLastname.getText().trim();
        String quantity = txtCourse.getText().trim();

        if (product_name.isEmpty() || price.isEmpty() || quantity.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all product details!");
            return;
        }

        String sql = "INSERT INTO products (product_name, price, quantity) VALUES (?, ?, ?)";

        try (Connection conn = MsConnectAccess.conn();
            PreparedStatement pst = conn.prepareStatement(sql)) {

            pst.setString(1, product_name);
            pst.setString(2, price);
            pst.setString(3, quantity);

            int rowsInserted = pst.executeUpdate();

            if (rowsInserted > 0) {
                JOptionPane.showMessageDialog(this, "Student added successfully!");

                txtId.setText("");
                txtFirstname.setText("");
                txtLastname.setText("");
                txtCourse.setText("");

                loadTableData();
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error adding student: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        String id = txtId.getText().trim();

        if (id.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a product from the table to delete!");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete product ID: " + id + "?",
            "Confirm Deletion",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE
        );

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        String sql = "DELETE FROM products WHERE ID = ?";

        try (Connection conn = MsConnectAccess.conn();
            PreparedStatement pst = conn.prepareStatement(sql)) {

            pst.setString(1, id);

            int rowsDeleted = pst.executeUpdate();

            if (rowsDeleted > 0) {
                JOptionPane.showMessageDialog(this, "Student deleted successfully!");
                clearFields();
                loadTableData();
            } else {
                JOptionPane.showMessageDialog(this, "Record not found.");
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error deleting student: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        String id = txtId.getText().trim();
        String product_name = txtFirstname.getText().trim();
        String price = txtLastname.getText().trim();
        String quantity = txtCourse.getText().trim();

        if (id.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a productt from the table first!");
            return;
        }

        if (product_name.isEmpty() || price.isEmpty() || quantity.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all fields to update!");
            return;
        }

        String sql = "UPDATE products SET product_name = ?, price = ?, quantity = ? WHERE ID = ?";

        try (Connection conn = MsConnectAccess.conn();
            PreparedStatement pst = conn.prepareStatement(sql)) {

            pst.setString(1, product_name);
            pst.setString(2, price);
            pst.setString(3, quantity);
            pst.setString(4, id);

            int rowsUpdated = pst.executeUpdate();

            if (rowsUpdated > 0) {
                JOptionPane.showMessageDialog(this, "Product updated successfully!");
                clearFields();
                loadTableData();
            } else {
                JOptionPane.showMessageDialog(this, "Record not found or no changes made.");
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error updating student: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton3ActionPerformed

