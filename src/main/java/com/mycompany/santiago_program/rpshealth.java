    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:

        int p1 = Integer.parseInt(txt1.getText());
        int p2 = Integer.parseInt(txt2.getText());
        int p1h = Integer.parseInt(jTextField3.getText());
        int p2h = Integer.parseInt(jTextField4.getText());

        if(p1 == 1 && p2 == 1)
        {
            JOptionPane.showMessageDialog(rootPane, "DRAW", "RPS", HEIGHT);
        }
        else if(p1 == 1 && p2 == 2)
        {
            JOptionPane.showMessageDialog(rootPane, "PLAYER 2 WINS!", "RPS", HEIGHT);
            int d = p1h - 1;
            jTextField3.setText(""+d);
        }
        else if(p1 == 1 && p2 == 3)
        {
            JOptionPane.showMessageDialog(rootPane, "PLAYER 1 WINS!", "RPS", HEIGHT);
            int d = p2h - 1;
            jTextField4.setText(""+d);
        }
        else if(p1 == 2 && p2 == 1)
        {
            JOptionPane.showMessageDialog(rootPane, "PLAYER 1 WINS!", "RPS", HEIGHT);
            int d = p2h - 1;
            jTextField4.setText(""+d);
        }
        else if(p1 == 2 && p2 == 2)
        {
            JOptionPane.showMessageDialog(rootPane, "DRAW!", "RPS", HEIGHT);
        }
        else if(p1 == 2 && p2 == 3)
        {
            JOptionPane.showMessageDialog(rootPane, "PLAYER 2 WINS!", "RPS", HEIGHT);
            int d = p1h - 1;
            jTextField3.setText(""+d);
        }
        else if(p1 == 3 && p2 == 1)
        {
            JOptionPane.showMessageDialog(rootPane, "PLAYER 2 WINS!", "RPS", HEIGHT);
            int d = p1h - 1;
            jTextField3.setText(""+d);
        }
        else if(p1 == 3 && p2 == 2)
        {
            JOptionPane.showMessageDialog(rootPane, "PLAYER 1 WINS!", "RPS", HEIGHT);
            int d = p2h - 1;
            jTextField4.setText(""+d);
        }
        else if(p1 == 3 && p2 == 3)
        {
            JOptionPane.showMessageDialog(rootPane, "DRAW", "RPS", HEIGHT);
        }

        if (p1 == 0) {
            JOptionPane.showMessageDialog(rootPane, "Winner Player 2!", "RPS", HEIGHT);
        } else if (p2 == 0)
        {
            JOptionPane.showMessageDialog(rootPane, "Winner Player 1!", "RPS", HEIGHT);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

